#!/usr/bin/env python3
"""Render INDEX.md from the corpus registry.

Run from the repository root:

    python3 corpus/build_index.py          # write INDEX.md
    python3 corpus/build_index.py --check   # fail if INDEX.md is stale

INDEX.md is generated, never hand-edited: edit corpus/nodes.json instead.
Standard library only.
"""

import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "INDEX.md")

ARM_TITLES = {
    "readout": "Readout — what can be read off a person",
    "steering": "Steering — how far a person can be moved",
    "both": "Bridges — nodes that join readout to steering",
    "evidence": "Evidence — verified external literature",
}
ARM_ORDER = ["readout", "both", "steering", "evidence"]


def load(name):
    with open(os.path.join(ROOT, "corpus", name), encoding="utf-8") as fh:
        return json.load(fh)


def cell(value):
    """One table cell: never empty, never break the table."""
    if value is None or value == "":
        return "—"
    return str(value).replace("|", "\\|").replace("\n", " ")


def render(nodes_doc, refs_doc):
    nodes = nodes_doc["nodes"]
    refs = {r["id"]: r for r in refs_doc["references"]}
    by_arm = {a: [n for n in nodes if n["arm"] == a] for a in ARM_ORDER}

    L = []
    w = L.append

    w("# Corpus index")
    w("")
    w("Generated by `corpus/build_index.py` from `corpus/nodes.json`. Do not edit by hand.")
    w("")
    w("Every node of this tree, what decision it studies, what moves that decision, and")
    w("what it is allowed to claim. Walk down from here. For the argument these nodes add")
    w("up to, read [README.md](README.md); for the rules this file is checked against, read")
    w("[corpus/README.md](corpus/README.md).")
    w("")
    w("Checked by `python3 corpus/validate_corpus.py`: every path below exists, every")
    w("number is traceable to a committed file, and every citation carries a resolvable")
    w("identifier and the date it was last confirmed.")
    w("")

    # The tree.
    w("## The tree")
    w("")
    w("```")
    w(".")
    # Group by the first two path components, so experiments/brain/x and
    # evidence/y land under their real parents rather than a guessed one.
    tops = {}
    for n in nodes:
        parts = n["path"].split("/")
        top = parts[0]
        group = parts[1] if len(parts) > 2 else None
        tops.setdefault(top, {}).setdefault(group, []).append(n)

    def label(n):
        t = n["task"] or ""
        return t if len(t) <= 88 else t[:85] + "..."

    top_names = sorted(tops, key=lambda t: (t != "experiments", t))
    for top in top_names:
        w("├── %s/" % top)
        groups = tops[top]
        gnames = sorted(groups, key=lambda g: (g is None, g))
        for gi, g in enumerate(gnames):
            glast = gi == len(gnames) - 1
            items = sorted(groups[g], key=lambda n: n["id"])
            if g is None:
                for ni, n in enumerate(items):
                    nlast = glast and ni == len(items) - 1
                    w("│   %s── %-22s %s" % ("└" if nlast else "├", n["id"], label(n)))
                continue
            w("│   %s── %s/" % ("└" if glast else "├", g))
            for ni, n in enumerate(items):
                nlast = ni == len(items) - 1
                lead = "│   %s   %s── " % (" " if glast else "│", "└" if nlast else "├")
                w("%s%-22s %s" % (lead, n["id"], label(n)))
    w("└── corpus/            the registry this index is built from")
    w("```")
    w("")

    # The comparison table: the reason this file exists.
    w("## Decision setups, side by side")
    w("")
    w("The axis that matters when comparing these nodes is not the modality but the")
    w("decision: who is deciding, what structure the choice has, what is pushed on it,")
    w("and what is watching. Nodes that study representation rather than choice say so.")
    w("")
    w("| Node | Who decides | Task | What moves it | Readout | Defence | Substrate |")
    w("|---|---|---|---|---|---|---|")
    for arm in ARM_ORDER:
        for n in sorted(by_arm[arm], key=lambda n: n["id"]):
            w("| [`%s`](%s) | %s | %s | %s | %s | %s | %s |" % (
                n["id"], n["path"], cell(n["decider"]), cell(n["task"]),
                cell(n["manipulation"]), cell(n["readout"]), cell(n.get("defence")),
                cell(n["substrate"])))
    w("")

    # Human-data map: who touches real people.
    w("## Which nodes touch real human data")
    w("")
    w("No node in this tree runs an intervention on a person. The steering results are")
    w("in-silico. This table is the check on that sentence.")
    w("")
    w("| Node | Human data | Substrate | Status |")
    w("|---|---|---|---|")
    for arm in ARM_ORDER:
        for n in sorted(by_arm[arm], key=lambda n: n["id"]):
            w("| [`%s`](%s) | %s | %s | %s |" % (
                n["id"], n["path"], "yes" if n["human_data"] else "no",
                cell(n["substrate"]), cell(n["status"])))
    w("")

    # Per-node cards.
    for arm in ARM_ORDER:
        if not by_arm[arm]:
            continue
        w("## %s" % ARM_TITLES[arm])
        w("")
        for n in sorted(by_arm[arm], key=lambda n: n["id"]):
            w("### [`%s`](%s)" % (n["id"], n["path"]))
            w("")
            w("**%s**" % n["question"])
            w("")
            w("- **Setup** — %s deciding on %s; %s; measured as %s." % (
                n["decider"], n["task"], n["manipulation"], n["readout"]))
            if n.get("defence"):
                w("- **Defence** — %s" % n["defence"])
            w("- **Status** — %s" % n["status"])
            if n.get("depends_on"):
                w("- **Builds on** — %s" % ", ".join(
                    "[`%s`](#%s)" % (d, d) for d in n["depends_on"]))
            if n.get("key_numbers"):
                w("- **Numbers**")
                for num in n["key_numbers"]:
                    w("  - %s: **%s** — [`%s`](%s)" % (
                        num["what"], num["value"], num["source"], num["source"]))
            if n.get("caveats"):
                w("- **Does not show**")
                for c in n["caveats"]:
                    w("  - %s" % c)
            if n.get("provenance_files"):
                w("- **Provenance** — %s" % ", ".join(
                    "[`%s`](%s)" % (os.path.basename(p), p)
                    for p in n["provenance_files"]))
            if n.get("cites"):
                w("- **Cites** — %s" % ", ".join(
                    "%s (%s)" % (refs[c]["id"], refs[c]["status"])
                    if c in refs else "%s (MISSING)" % c
                    for c in n["cites"]))
            w("")

    counts = {}
    for r in refs.values():
        counts[r["status"]] = counts.get(r["status"], 0) + 1
    w("## External citations")
    w("")
    w("`corpus/references.json` holds %d citations: %s. Only `verified` entries may"
      % (len(refs), ", ".join("%d %s" % (v, k) for k, v in sorted(counts.items()))))
    w("support a claim. `unverified` entries are kept deliberately, with the reason they")
    w("could not be confirmed, so that nobody quietly re-adds them later.")
    w("")
    return "\n".join(L) + "\n"


def main():
    text = render(load("nodes.json"), load("references.json"))
    check = "--check" in sys.argv
    if check:
        if not os.path.exists(OUT):
            print("INDEX.md does not exist; run: python3 corpus/build_index.py")
            return 1
        with open(OUT, encoding="utf-8") as fh:
            if fh.read() != text:
                print("INDEX.md is stale; run: python3 corpus/build_index.py")
                return 1
        print("INDEX.md is up to date.")
        return 0
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write(text)
    print("wrote INDEX.md (%d nodes)" % len(load("nodes.json")["nodes"]))
    return 0


if __name__ == "__main__":
    sys.exit(main())
